// Builds server/facts/birdTraits.ts from EltonTraits 1.0 (Wilman et al. 2014, CC0).
// Usage: node scripts/build-bird-traits.mjs [path/to/BirdFuncDat.txt]
// (downloads BirdFuncDat.txt from figshare when no local copy is given)
// Names follow BirdLife (2014); each is also matched against the GBIF backbone so renamed
// species are found under their current name.
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'https://ndownloader.figshare.com/files/5631081'; // BirdFuncDat.txt
const UA = 'FieldLens/1.0 (https://github.com/mint-morrogh/FieldLens; build script)';

const text = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch(SOURCE, { headers: { 'User-Agent': UA } })).text();
const [header, ...lines] = text.trim().split(/\r?\n/);
const cols = header.split('\t');
const col = (row, name) => row[cols.indexOf(name)];

const DIET = ['Inv', 'Vend', 'Vect', 'Vfish', 'Vunk', 'Scav', 'Fruit', 'Nect', 'Seed', 'PlantO'];
// Foraging strata, as one-letter codes.
const STRATA = [
  ['U', 'ForStrat-watbelowsurf'],
  ['W', 'ForStrat-wataroundsurf'],
  ['G', 'ForStrat-ground'],
  ['L', 'ForStrat-understory'],
  ['M', 'ForStrat-midhigh'],
  ['C', 'ForStrat-canopy'],
  ['A', 'ForStrat-aerial'],
];
const percentages = (r, pairs) =>
  pairs
    .map(([k, c]) => [k, Number(col(r, c)) || 0])
    .filter(([, v]) => v > 0)
    .map(([k, v]) => `${k}${v}`)
    .join(',');

const rows = lines
  .map((l) => l.split('\t'))
  .filter((r) => col(r, 'Scientific'))
  .map((r) => {
    const mass = Number(col(r, 'BodyMass-Value'));
    const diet = percentages(
      r,
      DIET.map((k) => [k, `Diet-${k}`]),
    );
    const strata = percentages(r, STRATA);
    return {
      name: col(r, 'Scientific').trim(),
      entry: {
        ...(Number.isFinite(mass) && mass > 0 ? { m: Math.round(mass * 10) / 10 } : {}),
        ...(col(r, 'Nocturnal') === '1' ? { n: 1 } : {}),
        ...(diet ? { d: diet } : {}),
        ...(strata ? { f: strata } : {}),
      },
    };
  })
  .filter((r) => Object.keys(r.entry).length > 0);

async function accepted(name) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(
        `https://api.gbif.org/v1/species/match?kingdom=Animalia&class=Aves&name=${encodeURIComponent(name)}`,
        { headers: { 'User-Agent': UA } },
      );
      const m = await res.json();
      if (m.rank === 'SPECIES' && m.species && m.matchType !== 'NONE') return m.species;
      return undefined;
    } catch {
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
  return undefined;
}

const out = {};
let renamed = 0;
let next = 0;
async function worker() {
  while (next < rows.length) {
    const { name, entry } = rows[next++];
    const key = name.toLowerCase();
    out[key] = entry;
    const current = await accepted(name);
    if (current && current.toLowerCase() !== key) {
      out[current.toLowerCase()] ??= entry;
      renamed++;
    }
  }
}
await Promise.all(Array.from({ length: 12 }, worker));

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  'server/facts/birdTraits.ts',
  `/**
 * Bird traits bundled from EltonTraits 1.0 — Wilman, H. et al. (2014), Ecology 95:2027,
 * https://doi.org/10.6084/m9.figshare.3559887.v1 — CC0. Generated by
 * scripts/build-bird-traits.mjs; do not edit by hand. Keys are lower-case binomials.
 * m: typical adult body mass in grams; n: 1 when mainly nocturnal (otherwise diurnal)
 * d: diet percentages, same codes as MAMMAL_TRAITS, e.g. "Inv20,Vend10,Fruit20,Seed50"
 * f: foraging strata percentages — U under water, W on the water surface, G ground,
 *    L understory, M mid-height, C canopy, A aerial, e.g. "G40,L20,M20,C20"
 */
export const BIRD_TRAITS: Record<string, { m?: number; n?: 1; d?: string; f?: string }> = ${JSON.stringify(sorted)};
`,
);
console.log(
  `Wrote ${Object.keys(sorted).length} names (${rows.length} species, ${renamed} renamed).`,
);
