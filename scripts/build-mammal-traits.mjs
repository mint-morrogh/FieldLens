// Builds server/facts/mammalTraits.ts from EltonTraits 1.0 (Wilman et al. 2014, CC0).
// Usage: node scripts/build-mammal-traits.mjs
// EltonTraits uses Mammal Species of the World 3 (2005) names; each name is also matched
// against the GBIF backbone so renamed species (e.g. Neovison vison → Neogale vison) are found.
import { writeFileSync } from 'node:fs';

const SOURCE = 'https://ndownloader.figshare.com/files/5631084'; // MamFuncDat.txt
const UA = 'FieldLens/1.0 (https://github.com/mint-morrogh/FieldLens; build script)';

const text = await (await fetch(SOURCE, { headers: { 'User-Agent': UA } })).text();
const [header, ...lines] = text.trim().split(/\r?\n/);
const cols = header.split('\t');
const col = (row, name) => row[cols.indexOf(name)];

const DIET = ['Inv', 'Vend', 'Vect', 'Vfish', 'Vunk', 'Scav', 'Fruit', 'Nect', 'Seed', 'PlantO'];

const rows = lines
  .map((l) => l.split('\t'))
  .filter((r) => col(r, 'Scientific'))
  .map((r) => {
    const diet = DIET.map((k) => [k, Number(col(r, `Diet-${k}`)) || 0])
      .filter(([, v]) => v > 0)
      .map(([k, v]) => `${k}${v}`)
      .join(',');
    const activity =
      (col(r, 'Activity-Nocturnal') === '1' ? 'N' : '') +
      (col(r, 'Activity-Crepuscular') === '1' ? 'C' : '') +
      (col(r, 'Activity-Diurnal') === '1' ? 'D' : '');
    const mass = Number(col(r, 'BodyMass-Value'));
    return {
      name: col(r, 'Scientific').trim(),
      entry: {
        ...(Number.isFinite(mass) && mass > 0 ? { m: Math.round(mass * 10) / 10 } : {}),
        ...(diet ? { d: diet } : {}),
        ...(activity ? { a: activity } : {}),
        ...(col(r, 'ForStrat-Value') ? { f: col(r, 'ForStrat-Value').trim() } : {}),
      },
    };
  });

async function accepted(name) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(
        `https://api.gbif.org/v1/species/match?kingdom=Animalia&class=Mammalia&name=${encodeURIComponent(name)}`,
        { headers: { 'User-Agent': UA } },
      );
      const m = await res.json();
      if (m.rank === 'SPECIES' && m.species && m.matchType !== 'NONE') return m.species;
      return undefined;
    } catch {
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
  return undefined;
}

const out = {};
let renamed = 0;
let next = 0;
async function worker() {
  while (next < rows.length) {
    const { name, entry } = rows[next++];
    const key = name.toLowerCase();
    out[key] = entry;
    const current = await accepted(name);
    if (current && current.toLowerCase() !== key) {
      out[current.toLowerCase()] ??= entry;
      renamed++;
    }
  }
}
await Promise.all(Array.from({ length: 8 }, worker));

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  'server/facts/mammalTraits.ts',
  `/**
 * Mammal traits bundled from EltonTraits 1.0 — Wilman, H. et al. (2014) "EltonTraits 1.0:
 * Species-level foraging attributes of the world's birds and mammals", Ecology 95:2027,
 * https://doi.org/10.6084/m9.figshare.3559887.v1 — CC0. Generated by
 * scripts/build-mammal-traits.mjs; do not edit by hand. Keys are lower-case binomials (the
 * original MSW3 name and, when different, the current GBIF name).
 * m: typical adult body mass in grams
 * d: diet percentages, e.g. "Inv70,Scav10,Fruit20" (Inv invertebrates, Vend mammals & birds,
 *    Vect reptiles & amphibians, Vfish fish, Vunk other vertebrates, Scav carrion, Fruit, Nect
 *    nectar, Seed, PlantO other plant material)
 * a: activity — N nocturnal, C crepuscular, D diurnal
 * f: foraging stratum — M marine, G ground, S scansorial, Ar arboreal, A aerial
 */
export const MAMMAL_TRAITS: Record<string, { m?: number; d?: string; a?: string; f?: string }> = ${JSON.stringify(sorted)};
`,
);
console.log(
  `Wrote ${Object.keys(sorted).length} names (${rows.length} species, ${renamed} renamed).`,
);
