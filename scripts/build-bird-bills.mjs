// Builds server/facts/birdBills.ts from AVONET (Tobias et al. 2022, Ecology Letters 25:581, CC BY 4.0).
// Usage: node scripts/build-bird-bills.mjs   (needs the `unzip` command)
// Names follow BirdLife; each is also matched against the GBIF backbone so renamed
// species are found under their current name.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const SOURCE = 'https://ndownloader.figshare.com/files/38429873'; // ELEData.zip
const CSV = 'ELEData/TraitData/AVONET1_BirdLife.csv';
const UA = 'FieldLens/1.0 (https://github.com/mint-morrogh/FieldLens; build script)';
/** Orders whose bills are hooked (raptors, owls, parrots) or flat (ducks, geese, swans). */
const HOOKED = new Set([
  'Accipitriformes',
  'Cathartiformes',
  'Falconiformes',
  'Strigiformes',
  'Psittaciformes',
]);
const FLAT = new Set(['Anseriformes']);

const dir = mkdtempSync(join(tmpdir(), 'avonet-'));
const zip = join(dir, 'ELEData.zip');
writeFileSync(
  zip,
  Buffer.from(await (await fetch(SOURCE, { headers: { 'User-Agent': UA } })).arrayBuffer()),
);
const text = execFileSync('unzip', ['-p', zip, CSV], { maxBuffer: 64 * 1024 * 1024 }).toString(
  'latin1',
);
rmSync(dir, { recursive: true, force: true });

/** Minimal RFC 4180 parser: quoted fields may contain commas, quotes and newlines. */
function parseCsv(src) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"' && src[i + 1] === '"') ((field += '"'), i++);
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') (row.push(field), (field = ''));
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++;
      (row.push(field), rows.push(row), (row = []), (field = ''));
    } else field += ch;
  }
  if (field || row.length) (row.push(field), rows.push(row));
  return rows;
}

const [header, ...lines] = parseCsv(text);
const col = (r, name) => r[header.indexOf(name)];
const round2 = (x) => Math.round(x * 100) / 100;

const rows = lines
  .filter((r) => col(r, 'Species1'))
  .map((r) => {
    const length = Number(col(r, 'Beak.Length_Culmen'));
    const depth = Number(col(r, 'Beak.Depth'));
    const wing = Number(col(r, 'Wing.Length'));
    const order = col(r, 'Order1');
    if (!(length > 0 && depth > 0 && wing > 0)) return undefined;
    return {
      name: col(r, 'Species1').trim(),
      entry: {
        t: round2(depth / length),
        l: round2(length / wing),
        ...(HOOKED.has(order) ? { o: 'h' } : FLAT.has(order) ? { o: 'f' } : {}),
      },
    };
  })
  .filter(Boolean);

async function accepted(name) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(
        `https://api.gbif.org/v1/species/match?kingdom=Animalia&class=Aves&name=${encodeURIComponent(name)}`,
        { headers: { 'User-Agent': UA } },
      );
      const m = await res.json();
      if (m.rank === 'SPECIES' && m.species && m.matchType !== 'NONE') return m.species;
      return undefined;
    } catch {
      await new Promise((r) => setTimeout(r, 1000));
    }
  }
  return undefined;
}

const out = {};
let renamed = 0;
let next = 0;
async function worker() {
  while (next < rows.length) {
    const { name, entry } = rows[next++];
    const key = name.toLowerCase();
    out[key] = entry;
    const current = await accepted(name);
    if (current && current.toLowerCase() !== key) {
      out[current.toLowerCase()] ??= entry;
      renamed++;
    }
  }
}
await Promise.all(Array.from({ length: 12 }, worker));

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  'server/facts/birdBills.ts',
  `/**
 * Bird bill shapes from AVONET — Tobias, J.A. et al. (2022), Ecology Letters 25:581,
 * https://doi.org/10.1111/ele.13898 — CC BY 4.0. Generated by scripts/build-bird-bills.mjs;
 * do not edit by hand. Keys are lower-case binomials.
 * t: bill depth ÷ culmen length (thickness); l: culmen length ÷ wing length;
 * o: 'h' for hooked-bill orders (raptors, owls, parrots), 'f' for ducks, geese and swans
 */
export const BIRD_BILLS: Record<string, { t: number; l: number; o?: 'h' | 'f' }> = ${JSON.stringify(sorted)};
`,
);
console.log(
  `Wrote ${Object.keys(sorted).length} names (${rows.length} species, ${renamed} renamed).`,
);
